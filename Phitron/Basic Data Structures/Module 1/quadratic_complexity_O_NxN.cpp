//Quadratic Complexity O(N*N)

#include <bits/stdc++.h>
using namespace std;
int main() {

    int n; // O(1)
    cin >> n; // O(1)

    for (int i = 0; i < n; i++) // O(N)
    {
        for (int j = 0; j < n; j++) // O(N)
        {
            cout << "Hello" << endl;
        }
    }

    return 0; // O(1)
}
